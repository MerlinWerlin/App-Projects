// Bakes generated template sets into finished path strings (T117, D110-1).
// The generator modules in src/core/templateArt/<set>.ts build their outlines with occlude.ts and helper geometry,
// which took seconds at import. This script runs each generator once and writes
// src/core/templateArt/baked/<set>.ts holding the finished Template objects; src/core/templates.ts imports only the
// baked files, so the app never runs generation code. The generators stay the source of truth:
// src/core/templateArt/baked/baked.test.ts checks baked == generated.
//
// Usage: node scripts/bake-templates.ts           # rewrite every baked file
//        node scripts/bake-templates.ts --check   # exit 1 if any baked file is stale
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BAKED_SETS } from '../src/core/templateArt/baked/sets.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'src/core/templateArt/baked');
const check = process.argv.includes('--check');

export function bakedSource(name: string, file: string, templates: readonly unknown[]): string {
  const rows = templates.map((t) => `  ${JSON.stringify(t)},`).join('\n');
  return (
    `// GENERATED by scripts/bake-templates.ts from ../${file}.ts — do not edit by hand.\n` +
    `// Change the generator, then run: node scripts/bake-templates.ts\n` +
    `import type { Template } from '../../templates.ts';\n\n` +
    `export const ${name}: Template[] = [\n${rows}\n];\n`
  );
}

let stale = 0;
mkdirSync(outDir, { recursive: true });
for (const { name, file } of BAKED_SETS) {
  const mod = await import(join(root, 'src/core/templateArt', `${file}.ts`));
  const set = mod[name] as unknown[];
  if (!Array.isArray(set)) throw new Error(`${file}.ts does not export ${name}`);
  const src = bakedSource(name, file, set);
  const path = join(outDir, `${file}.ts`);
  const old = existsSync(path) ? readFileSync(path, 'utf8') : '';
  if (old === src) continue;
  stale++;
  if (check) console.error(`stale: ${path}`);
  else {
    writeFileSync(path, src);
    console.log(`baked ${name}: ${set.length} templates, ${(src.length / 1024).toFixed(0)} KB`);
  }
}
if (check && stale) process.exit(1);
console.log(check ? 'baked files up to date' : `done (${stale} written)`);
