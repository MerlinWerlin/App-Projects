#!/usr/bin/env python3
"""Convert OpenCV's LBP frontal-face cascade (XML) into compact TypeScript data for src/core/faceDetect.ts.

Source: lbpcascade_frontalface_opencv.xml from the OpenCV project's data/lbpcascades
(as shipped with scikit-image's sample data). OpenCV licence: see docs/THIRD_PARTY.md.

Usage: python3 scripts/gen-face-cascade.py [path/to/lbpcascade_frontalface_opencv.xml]
Writes src/core/faceCascade.ts.
"""
import pathlib
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT = '/usr/local/lib/python3.13/dist-packages/skimage/data/lbpcascade_frontalface_opencv.xml'


def main() -> None:
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT
    root = ET.parse(src).getroot()
    c = root.find('cascade')
    assert c.find('featureType').text.strip() == 'LBP'
    win_w = int(c.find('width').text)
    win_h = int(c.find('height').text)
    feats = []
    for f in c.find('features'):
        x, y, w, h = (int(v) for v in f.find('rect').text.split())
        feats += [x, y, w, h]
    stages = []  # [nWeak, threshold]
    weak = []  # per weak: featureIdx, 8 subset ints, leaf0, leaf1
    for st in c.find('stages'):
        thr = float(st.find('stageThreshold').text)
        wcs = list(st.find('weakClassifiers'))
        stages += [len(wcs), thr]
        for wc in wcs:
            nodes = [int(v) for v in wc.find('internalNodes').text.split()]
            leaves = [float(v) for v in wc.find('leafValues').text.split()]
            assert len(nodes) == 11 and nodes[0] == 0 and nodes[1] == -1, nodes
            weak.append((nodes[2], nodes[3:11], leaves[0], leaves[1]))
    feat_idx = [w[0] for w in weak]
    subsets = [s for w in weak for s in w[1]]
    leaves = [v for w in weak for v in (w[2], w[3])]

    def ints(a):
        return ','.join(str(v) for v in a)

    def floats(a):
        return ','.join(repr(round(v, 7)) for v in a)

    out = f"""// Generated by scripts/gen-face-cascade.py from OpenCV's lbpcascade_frontalface_opencv.xml.
// Do not edit by hand. Licence: OpenCV (BSD-3-Clause), see docs/THIRD_PARTY.md.
export const CASCADE = {{
  width: {win_w},
  height: {win_h},
  /** x, y, cellW, cellH per feature (3x3 grid of cells). */
  features: Int16Array.of({ints(feats)}),
  /** Per stage: weak-classifier count, threshold. */
  stages: Float64Array.of({floats(stages)}),
  /** Per weak classifier: feature index. */
  featureIndex: Int16Array.of({ints(feat_idx)}),
  /** Per weak classifier: 8 x 32-bit category subset words. */
  subsets: Int32Array.of({ints(subsets)}),
  /** Per weak classifier: leaf value when the code is in the subset, then when it is not. */
  leaves: Float64Array.of({floats(leaves)}),
}};
"""
    (ROOT / 'src' / 'core' / 'faceCascade.ts').write_text(out)
    print(f'{len(stages) // 2} stages, {len(weak)} weak classifiers, {len(feats) // 4} features')


if __name__ == '__main__':
    main()
