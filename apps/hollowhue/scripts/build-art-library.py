"""Canonical build: approved singles, preserved released chains, and authored nested editions.

The raster compiler stays in import-illustrated-art.py. Its v1 geometry remains stable for saves.
Only new nested sources are added; build-time packing/metadata do not change any old path or ID.
"""
import hashlib
import importlib.util
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from pack_art import pack_art

spec = importlib.util.spec_from_file_location('compiler', ROOT / 'scripts/import-illustrated-art.py')
compiler = importlib.util.module_from_spec(spec)
spec.loader.exec_module(compiler)
Image, cv2, np = compiler.Image, compiler.cv2, compiler.np


def build():
    originals = json.loads((ROOT / 'scripts/art/illustrations.json').read_text())['artworks']
    nested_path = ROOT / 'scripts/art/nested-source.json'
    nested = json.loads(nested_path.read_text()) if nested_path.exists() else {'artworks': [], 'scenes': []}
    items = originals + nested['artworks']
    lookup = {item['id']: item for item in items}
    released = json.loads((ROOT / 'scripts/art/catalog-source.json').read_text())['scenes']
    cache = ROOT / '.expo/art-cache'
    cache.mkdir(parents=True, exist_ok=True)
    art, receipts = {}, []
    for item in items:
        source = ROOT / 'scripts/art/illustrations' / item['file']
        sha = hashlib.sha256(source.read_bytes()).hexdigest()
        cached = cache / f"{item['id']}-{sha}-v1.json"
        if cached.exists():
            value, receipt = json.loads(cached.read_text())
        else:
            value, receipt = compiler.bake(item)
            cached.write_text(json.dumps([value, receipt], separators=(',', ':')))
        art[item['id']] = value
        receipts.append(receipt)
        print(item['id'], receipt['fillableRegions'], flush=True)
    pack_art(ROOT, art)
    words = {}
    for scene in released:
        words[f"scene.{scene['id']}.title"] = scene['title']
        words[f"scene.{scene['id']}.blurb"] = scene['blurb']
        for i, ident in enumerate(scene['art']):
            words[f"scene.{scene['id']}.level.z{i:02}"] = lookup[ident]['name']
    single_data = []
    for item in originals:
        ident = 'art-' + item['id']
        single_data.append({'id': ident, 'art': item['id'], 'theme': item['category'], 'difficulty': item['level']})
        words[f'scene.{ident}.title'] = item['name']
        words[f'scene.{ident}.blurb'] = item['subject'].removeprefix('a ').capitalize().rstrip('.') + '.'
        words[f'scene.{ident}.level.z00'] = item['name']
    for scene in nested['scenes']:
        words[f"scene.{scene['id']}.title"] = scene['title']
        words[f"scene.{scene['id']}.blurb"] = scene['blurb']
        for i, level in enumerate(scene['levels']):
            words[f"scene.{scene['id']}.level.z{i:02}"] = level['label']
    (ROOT / 'src/i18n/catalog.ts').write_text('// Generated by scripts/build-art-library.py.\nexport const catalogWords = ' + json.dumps(words, indent=2, ensure_ascii=False) + ' as const;\n', encoding='utf-8')
    (ROOT / 'src/scenes/single-data.ts').write_text('// Approved independent pictures. Generated by scripts/build-art-library.py.\nexport const singleData = ' + json.dumps(single_data, indent=2) + ' as const;\n')
    (ROOT / 'src/scenes/nested-data.ts').write_text('// Authored semantic portals from scripts/art/nested-source.json.\nexport const nestedData = ' + json.dumps(nested['scenes'], indent=2) + ' as const;\n')
    (ROOT / 'scripts/art/nested-receipts.json').write_text(json.dumps(receipts[len(originals):], indent=2) + '\n')
    covers = ROOT / 'assets/art-covers'
    cover_map = {}
    for item in originals:
        image = Image.open(ROOT / 'scripts/art/illustrations' / item['file']).convert('L')
        mask = (np.asarray(image) < 190).astype(np.uint8) * 255
        mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, np.ones((2, 2), np.uint8))
        cover = Image.new('RGB', image.size, (255, 255, 255))
        cover.paste((43, 38, 34), mask=Image.fromarray(mask))
        cover.thumbnail((720, 720), Image.Resampling.LANCZOS)
        filename = 'art-' + item['id'] + '.png'
        cover.save(covers / filename, optimize=True)
        cover_map['art-' + item['id']] = filename
    for scene in released:
        cover_map[scene['id']] = 'art-' + scene['art'][0] + '.png'
    for scene in nested['scenes']:
        cover_map[scene['id']] = 'art-' + scene['levels'][0]['art'] + '.png'
    (ROOT / 'src/scenes/art/covers.ts').write_text('// Generated lightweight gallery covers.\nexport const SCENE_COVERS: Record<string, number> = {\n' + ''.join(f'  "{ident}": require("../../../assets/art-covers/{filename}"),\n' for ident, filename in cover_map.items()) + '};\n')
    print('Packed', len(art), 'illustrations independently; originals remain byte-identical after decoding.')


if __name__ == '__main__':
    build()
