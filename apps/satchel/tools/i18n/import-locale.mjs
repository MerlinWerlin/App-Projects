// T21: imports translation drops from the OpenAI lane into the app (offline, no dependencies; Node 22.18+).
//
//   node tools/i18n/import-locale.mjs chunks            writes docs/spec/i18n_request/en.NN.json (the lane translates these)
//   node tools/i18n/import-locale.mjs <lang> <files...> merges the lane's chunk files for es|fr|de|ja, checks them
//                                                       (known keys, same {placeholders}, Satchel/OpenStreetMap kept),
//                                                       and writes src/i18n/locales/<lang>.ts + regenerates catalogs.ts
//   add --partial to bundle a language below the 95% coverage gate (testing only; never for a TestFlight build)
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { en } from '../../src/i18n/en.ts';
import { SUPPORTED } from '../../src/i18n/core.ts';
import { chunkCatalogue, coverage, mergeDrops, MIN_COVERAGE } from '../../src/i18n/localecheck.ts';

const root = resolve(new URL('../..', import.meta.url).pathname);
const [cmd, ...rest] = process.argv.slice(2);

if (cmd === 'chunks') {
  const dir = join(root, 'docs/spec/i18n_request');
  if (existsSync(dir)) for (const f of readdirSync(dir)) if (/^en\.\d+\.json$/.test(f)) rmSync(join(dir, f));
  mkdirSync(dir, { recursive: true });
  const chunks = chunkCatalogue(en, 400);
  chunks.forEach((c, i) => writeFileSync(join(dir, `en.${String(i + 1).padStart(2, '0')}.json`), JSON.stringify(c, null, 1) + '\n'));
  console.log(`${chunks.length} chunks, ${Object.keys(en).length} keys -> docs/spec/i18n_request/`);
  process.exit(0);
}

const lang = cmd;
if (!lang || lang === 'en' || !SUPPORTED.includes(lang)) {
  console.error(`usage: import-locale.mjs chunks | <${SUPPORTED.filter((l) => l !== 'en').join('|')}> <files...> [--partial]`);
  process.exit(2);
}
const partial = rest.includes('--partial');
const files = rest.filter((a) => a !== '--partial');
const drops = files.map((f) => JSON.parse(readFileSync(f, 'utf8')));
const { catalog, rejected } = mergeDrops(drops, en);
const cov = coverage(catalog, en);
console.log(`${lang}: ${Object.keys(catalog).length} accepted, ${rejected} rejected, coverage ${(cov * 100).toFixed(1)}%`);
if (cov < MIN_COVERAGE && !partial) {
  console.error(`not bundled: below ${MIN_COVERAGE * 100}% coverage (pass --partial only for local testing)`);
  process.exit(1);
}
const locDir = join(root, 'src/i18n/locales');
mkdirSync(locDir, { recursive: true });
const sorted = Object.fromEntries(Object.keys(en).filter((k) => k in catalog).map((k) => [k, catalog[k]]));
writeFileSync(
  join(locDir, `${lang}.ts`),
  `// Generated by tools/i18n/import-locale.mjs from the OpenAI lane's ${lang} drop. Do not edit by hand.\n` +
    `import type { Catalog } from '../core.ts';\n\nexport const ${lang}: Catalog = ${JSON.stringify(sorted, null, 1)};\n`,
);
const present = SUPPORTED.filter((l) => l !== 'en' && existsSync(join(locDir, `${l}.ts`)));
writeFileSync(
  join(root, 'src/i18n/catalogs.ts'),
  `// Bundled translations (synchronous, so startup never waits on them). English is the source in en.ts.\n` +
    `// Generated by tools/i18n/import-locale.mjs (T21); languages without a file fall back to English.\n` +
    `import type { Catalog, Lang } from './core.ts';\n` +
    present.map((l) => `import { ${l} } from './locales/${l}.ts';\n`).join('') +
    `\nexport const CATALOGS: Partial<Record<Lang, Catalog>> = {${present.length ? ' ' + present.join(', ') + ' ' : ''}};\n`,
);
console.log(`wrote src/i18n/locales/${lang}.ts and src/i18n/catalogs.ts (${present.join(', ')})`);
