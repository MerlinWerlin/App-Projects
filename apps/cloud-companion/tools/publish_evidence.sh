#!/usr/bin/env bash
set -euo pipefail
# Synthetic simulator screens and compile/test logs only; never signing material.
mkdir -p output
python3 - <<'PY'
import os,json
from pathlib import Path
keys=['CORE_RESULT','BUILD_RESULT','UI_RESULT','RENDER_RESULT']
Path('output/result.json').write_text(json.dumps({'source_sha':os.environ['GITHUB_SHA'],
    'run_id':os.environ['GITHUB_RUN_ID'], 'results':{k:os.environ.get(k) for k in keys}},indent=2)+'\n')
PY
evidence=$(mktemp -d "$RUNNER_TEMP/cloud-evidence.XXXXXX")
auth=$(git config --get http.https://github.com/.extraheader)
git -C "$evidence" init -q
git -C "$evidence" config http.https://github.com/.extraheader "$auth"
git -C "$evidence" remote add origin "https://github.com/$GITHUB_REPOSITORY.git"
if git -C "$evidence" fetch -q --depth=1 origin codex/cloud-companion-evidence; then
  git -C "$evidence" checkout -q -B evidence FETCH_HEAD
else
  git -C "$evidence" checkout -q --orphan evidence
fi
destination="$evidence/runs/$GITHUB_RUN_ID"
mkdir -p "$destination"
cp -R output/. "$destination/"
for log in core-tests.log native-build.log ui-tests.log; do
  if [ -f "$log" ]; then cp "$log" "$destination/"; fi
done
printf '%s\n' "$GITHUB_RUN_ID" > "$evidence/LATEST"
printf '%s\n' '# Cloud Companion native review evidence' '' 'Generated by the iOS CI workflow for the APPS Cloud Companion prototype. Each runs/ folder records its source commit, actual build/test outcomes, synthetic simulator screens and motion checks. This is review evidence, not product source or signed-device validation.' > "$evidence/README.md"
git -C "$evidence" config user.name 'Cloud Companion CI'
git -C "$evidence" config user.email 'cloud-companion-ci@users.noreply.github.com'
git -C "$evidence" add .
git -C "$evidence" commit -q -m "Native review evidence for $GITHUB_SHA"
git -C "$evidence" push -q origin HEAD:refs/heads/codex/cloud-companion-evidence
