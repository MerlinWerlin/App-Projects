// Renders the Glaze App Store screenshots (T67) from the HTML/SVG sources in assets/store/src/.
//
//   node assets/store/render.mjs            # chosen style -> assets/store/*.png (1290x2796)
//   node assets/store/render.mjs --style a  # one style only (a or b)
//   node assets/store/render.mjs --all      # both styles into assets/store/out/ (not committed)
//
// Steps: 1) read the real theme catalogue from src/core (so the theme count on the shots is the
// count we ship) and write src/catalogue.js; 2) open src/shot.html?style=X&shot=N in Chromium
// (430x932 CSS px at 3x = 1290x2796); 3) save PNGs; 4) shrink the committed PNGs with a
// 256-colour palette (PIL) when python3 + Pillow are present.
//
// Needs: Node 22.6+ (runs the .ts core files directly), the `playwright` package (global is fine)
// and a Chromium (default /opt/pw-browsers/chromium; override with CHROMIUM=/path/to/chrome).
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = join(here, '..', '..');
const CHOSEN = 'a'; // docs/STORE.md "Style choice"
const SHOTS = 8;

const args = process.argv.slice(2);
const all = args.includes('--all');
const styleArg = args.includes('--style') ? args[args.indexOf('--style') + 1] : null;
const styles = all ? ['a', 'b'] : [styleArg ?? CHOSEN];

// 1) Real catalogue -> src/catalogue.js
const { ALL_THEMES } = await import(pathToFileURL(join(repo, 'src/core/plusThemes.ts')).href);
const { SEASONAL_COLLECTIONS } = await import(pathToFileURL(join(repo, 'src/core/seasons.ts')).href);
const themes = ALL_THEMES.map((t) => ({
  id: t.id,
  name: t.name,
  plus: t.plus,
  palette: t.palette,
  widget: t.widget,
  categories: t.categories ?? [],
  displayFont: t.art?.displayFont ?? 'rounded',
}));
const data = {
  generatedFrom: 'src/core/plusThemes.ts ALL_THEMES + src/core/seasons.ts SEASONAL_COLLECTIONS',
  total: themes.length,
  free: themes.filter((t) => !t.plus).length,
  plus: themes.filter((t) => t.plus).length,
  themes,
  seasonal: SEASONAL_COLLECTIONS,
};
writeFileSync(join(here, 'src', 'catalogue.js'), `// Generated by assets/store/render.mjs. Do not edit.\nwindow.GLAZE_DATA = ${JSON.stringify(data, null, 1)};\n`);
console.log(`catalogue: ${data.total} themes (${data.free} free, ${data.plus} Plus)`);

// 2) Render
const require = createRequire(import.meta.url);
let playwright;
try {
  playwright = require('playwright');
} catch {
  const globalRoot = execFileSync('npm', ['root', '-g']).toString().trim();
  playwright = require(join(globalRoot, 'playwright'));
}
const executablePath = process.env.CHROMIUM ?? '/opt/pw-browsers/chromium';
const browser = await playwright.chromium.launch(existsSync(executablePath) ? { executablePath } : {});
const page = await browser.newPage({ viewport: { width: 430, height: 932 }, deviceScaleFactor: 3 });
const written = [];
for (const style of styles) {
  const outDir = all || style !== CHOSEN ? join(here, 'out') : here;
  mkdirSync(outDir, { recursive: true });
  for (let n = 1; n <= SHOTS; n++) {
    const url = pathToFileURL(join(here, 'src', 'shot.html')).href + `?style=${style}&shot=${n}`;
    await page.goto(url);
    await page.evaluate(() => document.fonts.ready);
    await page.waitForFunction(() => window.__ready === true);
    const file = join(outDir, `${outDir === here ? '' : style + '-'}${String(n).padStart(2, '0')}.png`);
    await page.screenshot({ path: file, clip: { x: 0, y: 0, width: 430, height: 932 } });
    written.push(file);
    console.log('wrote', file);
  }
}
await browser.close();

// 3) Palette-quantise (keeps 1290x2796, cuts size a lot). Skipped quietly without Pillow.
try {
  execFileSync('python3', [join(here, 'optimise.py'), ...written], { stdio: 'inherit' });
} catch {
  console.log('optimise.py skipped (needs python3 + Pillow); PNGs left unquantised');
}
