// One sprite source and byte-identical ActivityAttributes in the app and extension.
import { readFileSync, writeFileSync } from 'node:fs';
import { PETS } from '../src/core/islandPets.ts';
import { PET_COPY } from '../src/i18n/pets.ts';
const root = new URL('../', import.meta.url);
const artifacts = [
  ['targets/widget/GlazePetAttributes.swift', readFileSync(new URL('modules/glaze-island-pets/ios/GlazePetAttributes.swift', root), 'utf8')],
  ['targets/widget/IslandPetSprites.swift', `// Generated by scripts/island-pets-contract.mjs --write. Edit src/core/islandPets.ts.\nimport SwiftUI\n\nenum IslandPetSprites {\n  struct Sprite { let name: String; let color: Color; let rows: [String] }\n  static func pet(_ id: String) -> Sprite {\n    switch id {\n${PETS.map(p => {
    const rgb = [1, 3, 5].map(i => (parseInt(p.color.slice(i, i + 2), 16) / 255).toFixed(6));
    return `    case "${p.id}": return Sprite(name: "${p.name}", color: Color(red: ${rgb[0]}, green: ${rgb[1]}, blue: ${rgb[2]}), rows: [\n${p.rows.map(r => `      "${r}"`).join(',\n')}\n    ])`;
  }).join('\n')}\n    default: return pet("cat")\n    }\n  }\n}\n`],
];
for (const [locale, copy] of Object.entries(PET_COPY)) {
  const path = `targets/widget/${locale}.lproj/Localizable.strings`;
  const existing = readFileSync(new URL(path, root), 'utf8');
  const marker = '/* Island pets: generated from src/i18n/pets.ts */';
  const prefix = existing.split(marker)[0].trimEnd();
  const lines = ['open', 'happy', 'playful', 'sleepy'].map(key => `"pet.${key}" = ${JSON.stringify(copy[key])};`).join('\n');
  artifacts.push([path, `${prefix}\n\n${marker}\n${lines}\n`]);
}
for (const [path, expected] of artifacts) {
  const url = new URL(path, root);
  if (process.argv.includes('--write')) writeFileSync(url, expected);
  else if (readFileSync(url, 'utf8').replaceAll('\r\n', '\n') !== expected.replaceAll('\r\n', '\n')) {
    throw new Error(`${path} is out of sync; run node scripts/island-pets-contract.mjs --write`);
  }
}
console.log('Pet sprites and ActivityAttributes agree across app and extension.');
