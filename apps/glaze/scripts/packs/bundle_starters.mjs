#!/usr/bin/env node
// Glaze 1.0.38 (owner 2026-11-15: "keep R2 AND bundle a small starter set"): copy a few complete
// theme packs from the live pack host into the app, so Glaze looks complete offline and on first
// launch even when the host can't be reached.
//
//   node scripts/packs/bundle_starters.mjs --base https://pub-….r2.dev [--screen 2796] id1 id2 …
//
// For each id it reads the live catalogue entry and manifest, keeps exactly the files a phone with a
// `--screen`-pixel long edge downloads (assetsForDevice: one wallpaper size plus every thumb, hero and
// widget-art file), checks each file's size and SHA-256 against the manifest, and writes:
//   assets/starter-packs/<id>/<file>            the files (bundled by Metro as image assets)
//   src/generated/starterPacks.ts               catalogue entries, manifests and the require() map
// The app installs these through the same downloader as a real download (src/native/starterPacks.ts),
// so a bundled theme is byte-for-byte the downloaded one. Re-run after a pack changes on the host.
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assetsForDevice } from '../../src/core/packCatalog.ts';
import { packObjectUrl } from '../../src/core/packHost.ts';

const APP = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT_ASSETS = join(APP, 'assets', 'starter-packs');
const OUT_TS = join(APP, 'src', 'generated', 'starterPacks.ts');
const SAFE = /^[a-z0-9][a-z0-9._-]*$/;

const args = process.argv.slice(2);
const opt = (name, d) => (args.includes(name) ? args[args.indexOf(name) + 1] : d);
const base = opt('--base', '');
const screen = Number(opt('--screen', '2796'));
const ids = args.filter((a, i) => !a.startsWith('--') && !['--base', '--screen'].includes(args[i - 1]));
if (!/^https:\/\//.test(base) || !ids.length) {
  console.error('usage: --base <https pack host> [--screen 2796] <pack ids…>');
  process.exit(2);
}

const get = async (url) => {
  for (let i = 0; ; i++) {
    const r = await fetch(url, { signal: AbortSignal.timeout(60_000) }).catch((e) => ({ ok: false, status: String(e) }));
    if (r.ok) return Buffer.from(await r.arrayBuffer());
    if (i >= 3) throw new Error(`${url}: HTTP ${r.status}`);
    await new Promise((ok) => setTimeout(ok, 1000 * (i + 1)));
  }
};

const catalog = JSON.parse(String(await get(`${packObjectUrl(base, 'catalog.json')}?bundle=${Date.now()}`)));
rmSync(OUT_ASSETS, { recursive: true, force: true });
const packs = [];
let total = 0;
for (const id of ids) {
  if (!SAFE.test(id)) throw new Error(`bad id ${id}`);
  const entry = catalog.packs.find((p) => p.id === id);
  if (!entry) throw new Error(`${id}: not in the live catalogue`);
  if (entry.plus) throw new Error(`${id}: a Plus pack can't be a free starter`);
  const manifest = JSON.parse(String(await get(packObjectUrl(base, entry.manifest))));
  if (manifest.id !== id || manifest.packVersion !== entry.packVersion) throw new Error(`${id}: manifest does not match the catalogue`);
  const folder = entry.manifest.replace(/manifest\.json$/, '');
  const files = [];
  for (const a of assetsForDevice(manifest, screen)) {
    if (!SAFE.test(a.path)) throw new Error(`${id}: unsafe file name ${a.path}`);
    const bytes = await get(packObjectUrl(base, `${folder}${a.path}`));
    if (bytes.length !== a.bytes || createHash('sha256').update(bytes).digest('hex') !== a.sha256) throw new Error(`${id}/${a.path}: bytes differ from the manifest`);
    mkdirSync(join(OUT_ASSETS, id), { recursive: true });
    writeFileSync(join(OUT_ASSETS, id, a.path), bytes);
    files.push(a.path);
    total += bytes.length;
  }
  const { release: _release, ...rest } = entry; // one folder tree: a starter never needs a release tag
  packs.push({ entry: rest, manifest, files });
  console.log(`${id} v${entry.packVersion}: ${files.length} files`);
}

const lines = [
  '// GENERATED by scripts/packs/bundle_starters.mjs. Do not edit by hand; re-run the script.',
  `// ${packs.length} starter packs, ${(total / 1e6).toFixed(2)} MB of files for a ${screen}-px screen.`,
  '/* eslint-disable */',
  "import type { CatalogPack, RemoteArtManifest } from '../core/packCatalog';",
  '',
  `export const STARTER_SCREEN_PX = ${screen};`,
  `export const STARTER_BYTES = ${total};`,
  '',
  'export type StarterPack = { entry: CatalogPack; manifest: RemoteArtManifest; files: Readonly<Record<string, number>> };',
  '',
  'export const STARTER_PACKS: readonly StarterPack[] = [',
];
for (const p of packs) {
  lines.push('  {');
  lines.push(`    entry: ${JSON.stringify(p.entry)} as CatalogPack,`);
  lines.push(`    manifest: ${JSON.stringify(p.manifest)} as RemoteArtManifest,`);
  lines.push('    files: {');
  for (const f of p.files) lines.push(`      ${JSON.stringify(f)}: require('../../assets/starter-packs/${p.entry.id}/${f}'),`);
  lines.push('    },');
  lines.push('  },');
}
lines.push('];', '');
mkdirSync(dirname(OUT_TS), { recursive: true });
writeFileSync(OUT_TS, lines.join('\n'));
console.log(`${packs.length} packs, ${readdirSync(OUT_ASSETS).length} folders, ${(total / 1e6).toFixed(2)} MB -> assets/starter-packs, src/generated/starterPacks.ts`);
