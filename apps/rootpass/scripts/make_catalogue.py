"""
Builds src/core/catalogue.ts from the stock research (rootpass-country-steel.json, 23 Nov 2026): steel sections and
pipe commonly listed by named merchants or mills in each country, with the source URL on every group.

  python scripts/make_catalogue.py <path to rootpass-country-steel.json>

Unverified groups stay empty (verified: false) and the app shows "enter your size" for them instead of guessing.
"""
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / 'src' / 'core' / 'catalogue.ts'


def num(s):
    """'1-1/2' -> 1.5, '50' -> 50."""
    s = str(s).strip()
    m = re.fullmatch(r'(\d+)-(\d+)/(\d+)', s)
    if m:
        return int(m[1]) + int(m[2]) / int(m[3])
    m = re.fullmatch(r'(\d+)/(\d+)', s)
    if m:
        return int(m[1]) / int(m[2])
    return float(s)


def pair(size):
    a, b = size.lower().split('x')
    return num(a), num(b)


def src_of(v, key):
    s = v.get(f'{key}_src') or (v.get(key) or {}).get('src') if isinstance(v.get(key), dict) else v.get(f'{key}_src')
    if isinstance(s, list):
        s = s[0]
    return s or ''


def group(v, key, conv):
    raw = v.get(key)
    verified = not (v.get(f'{key}_verified') is False) and bool(raw)
    note = v.get(f'{key}_note') or (raw.get('note') if isinstance(raw, dict) else None)
    if isinstance(raw, dict):
        items = raw.get('t') or raw.get('d') or []
        if raw.get('verified') is False:
            verified = False
    else:
        items = raw or []
    out = {'items': conv(items) if items else [], 'src': src_of(v, key), 'verified': verified}
    if v.get(f'{key}_verified_partial'):
        out['partial'] = True
    if note:
        out['note'] = note
    return out


def build(d):
    cats = {}
    for c in ['AU', 'NZ', 'GB', 'IE', 'US', 'CA']:
        v = d[c]
        unit = 'mm' if c in ('AU', 'NZ', 'GB', 'IE') else 'in'
        cat = {'unit': unit}
        cat['shs'] = group(v, 'shs', lambda xs: [{'a': pair(x['size'])[0], 'b': pair(x['size'])[1], 'walls': x['wall']} for x in xs])
        cat['rhs'] = group(v, 'rhs', lambda xs: [{'a': pair(x['size'])[0], 'b': pair(x['size'])[1], 'walls': x['wall']} for x in xs])
        cat['chs'] = group(v, 'chs', lambda xs: [{'od': x['od'], 'walls': x['wall']} for x in xs])
        cat['angle'] = group(v, 'angle', lambda xs: [{'a': pair(x['size'])[0], 'b': pair(x['size'])[1], 'walls': x['t']} for x in xs])
        cat['flat'] = group(v, 'flat', lambda xs: [{'a': x['w'], 'b': 0, 'walls': x['t']} for x in xs])
        cat['plate'] = group(v, 'plate', lambda xs: list(xs))
        cat['round'] = group(v, 'round', lambda xs: list(xs))
        L = v['lengths']
        srcs = L.get('src')
        if unit == 'mm':
            cat['lengths'] = {'unit': 'mm', 'tube': L.get('tube', []), 'bar': sorted(set(L.get('angle', []) + L.get('flat', []) + L.get('round', []))),
                              'src': srcs[0] if isinstance(srcs, list) else srcs}
        else:
            cat['lengths'] = {'unit': 'ft', 'tube': L.get('tube_ft', []), 'bar': sorted(set(L.get('angle_ft', []) + L.get('flat_ft', []) + L.get('round_ft', []))),
                              'src': srcs[0] if isinstance(srcs, list) else srcs}
        p = v['pipe']
        sizes = p['sizes']
        if sizes == 'same_as_GB':
            sizes = d['GB']['pipe']['sizes']
        if sizes == 'same_as_US':
            sizes = d['US']['pipe']['sizes']
        psrc = p.get('src')
        cat['pipe'] = {'series': p['series'].split('.')[0][:90], 'sizes': [{'name': s['name'], 'od': s['od'], 'walls': s['walls']} for s in sizes],
                       'src': psrc[0] if isinstance(psrc, list) else psrc}
        cat['notes'] = v.get('notes', '')
        cats[c] = cat
    return cats


def main():
    d = json.loads(pathlib.Path(sys.argv[1]).read_text(encoding='utf8'))
    cats = build(d)
    body = json.dumps(cats, indent=1, ensure_ascii=False)
    OUT.write_text(f'''/**
 * Stocked steel by country (generated by scripts/make_catalogue.py; do not edit by hand).
 *
 * Every group lists what at least one named merchant or mill catalogue showed on 23 Nov 2026; the URL is in each
 * group's `src`. Merchant names appear here only as sources: the app never shows them. Sizes are in the country's
 * listing unit (`unit`: mm, or inches for the US and Canada); stock lengths in mm or feet (`lengths.unit`).
 * A group with `verified: false` could not be confirmed and is empty: the app asks for a custom size instead.
 * Main sources: AU InfraBuild + Edcon Steel; NZ Vulcan (2024) + Steel & Tube; GB BM Steel; IE Ferrum (Dublin);
 * US Metals Depot; CA Russel Metals + Sureway Metal. Pipe walls: AS 1074 (AU/NZ), EN 10255 (GB/IE),
 * ASME B36.10M (US/CA).
 */
import type {{ CatalogueSet }} from './catalogueTypes.ts';

export const CATALOGUES: CatalogueSet = {body};
''', encoding='utf8')
    print('wrote', OUT, len(body), 'chars')


if __name__ == '__main__':
    main()
