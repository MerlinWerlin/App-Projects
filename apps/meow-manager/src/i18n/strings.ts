export function t(
  language: Language,
  key: Key,
  values: Record<string, string | number> = {},
): string {
  return Object.entries(values).reduce(
    (s, [k, v]) => s.replaceAll(`{${k}}`, String(v)),
    (language === "ja" ? ja : en)[key] as string,
  );
}
